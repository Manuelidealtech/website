function interpolate(value, variables = {}) {
  return String(value).replace(/\{(\w+)\}/g, (_, key) => variables[key] ?? `{${key}}`)
}

export function shopT(language, key, variables) {
  const dictionary = SHOP_TRANSLATIONS[language] || SHOP_TRANSLATIONS.it
  return interpolate(dictionary[key] ?? SHOP_TRANSLATIONS.it[key] ?? key, variables)
}

export function getLocalizedAvailability(product, language = 'it') {
  if (product?.track_stock && Number(product.stock_quantity || 0) <= 0) {
    return { available: false, label: shopT(language, 'soldOut') }
  }

  if (product?.track_stock && Number(product.stock_quantity || 0) <= 5) {
    return {
      available: true,
      label: shopT(language, 'lastAvailable', { count: product.stock_quantity }),
    }
  }

  return { available: true, label: shopT(language, 'available') }
}

export function localizedCountry(language = 'it') {
  if (language === 'en') return 'Italy'
  if (language === 'tr') return 'İtalya'
  return 'Italia'
}
